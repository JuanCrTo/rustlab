#!/usr/bin/env python3
"""Genera los `mod.rs` / `lib.rs` automáticamente.

Uso (desde la raíz del workspace):  python3 scripts/gen_mods.py

- Recorre <crate>/src de cada crate del workspace.
- Por cada carpeta lista sus subcarpetas y archivos .rs como `pub mod x;`.
- Solo reescribe archivos vacíos o que empiecen con la marca AUTO-GENERATED.
  Si escribes código a mano en un mod.rs, quita la marca y el script lo respeta.
"""
import pathlib

MARK = "// AUTO-GENERATED by scripts/gen_mods.py - no editar a mano\n"
ROOT = pathlib.Path(__file__).resolve().parent.parent


def generated(path: pathlib.Path) -> bool:
    if not path.exists() or path.stat().st_size == 0:
        return True
    return path.read_text().startswith(MARK)


def process(directory: pathlib.Path, index: pathlib.Path) -> None:
    names = []
    for child in sorted(directory.iterdir()):
        if child.is_dir():
            names.append(child.name)
            process(child, child / "mod.rs")
        elif child.suffix == ".rs" and child.name not in ("mod.rs", "lib.rs", "main.rs"):
            names.append(child.stem)
    if generated(index):
        index.write_text(MARK + "".join(f"pub mod {n};\n" for n in names))


for src in sorted(ROOT.glob("*/src")):
    process(src, src / "lib.rs")
for src in sorted(ROOT.glob("projects/*/src")):
    pass  # los mini-proyectos son crates normales, se manejan a mano
